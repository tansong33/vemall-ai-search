DROP TABLE IF EXISTS product;
CREATE TABLE product (
    id              BIGINT PRIMARY KEY AUTO_INCREMENT,
    title           VARCHAR(200)  NOT NULL COMMENT '商品标题',
    category        VARCHAR(50)   NOT NULL COMMENT '类目',
    brand           VARCHAR(50)            COMMENT '品牌',
    price           DECIMAL(10,2) NOT NULL COMMENT '售价(元)',
    attrs           VARCHAR(500)           COMMENT '核心属性, JSON字符串',
    scene_tags      VARCHAR(200)           COMMENT '场景标签, 逗号分隔: 夏季,员工福利,送礼...',
    stock           INT           NOT NULL DEFAULT 0 COMMENT '库存',
    points_eligible TINYINT(1)    NOT NULL DEFAULT 1 COMMENT '是否可用福利积分',
    featured        TINYINT(1)    NOT NULL DEFAULT 0 COMMENT '是否主推',
    image_url       VARCHAR(300)           COMMENT '商品图URL',
    description     VARCHAR(1000)          COMMENT '卖点描述(建议用LLM离线扩写以提升语义召回)',
    INDEX idx_category (category),
    INDEX idx_price (price)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='商品表';

